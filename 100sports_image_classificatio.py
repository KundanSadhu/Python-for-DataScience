def create_image_split(dataframe, split_name):
    print(f"\nCreating {split_name} split...")

    count = 0

    for _, row in dataframe.iterrows():

        source_path = os.path.join(
            "/content/data",
            row["filepaths"]
        )

        class_name = str(row["labels"])

        destination_dir = os.path.join(
            base_split_path,
            split_name,
            class_name
        )

        os.makedirs(destination_dir, exist_ok=True)

        # Keep original filename
        destination_path = os.path.join(
            destination_dir,
            os.path.basename(row["filepaths"])
        )

        shutil.copy2(source_path, destination_path)

        count += 1

        if count % 1000 == 0:
            print(f"{count} images copied...")

    print(f"{split_name} complete: {count} images")


