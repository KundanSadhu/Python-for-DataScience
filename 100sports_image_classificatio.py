def count_parameters(model):
    """Counts the total number of trainable parameters in a model."""
    return sum(p.numel() for p in model.parameters() if p.requires_grad)

def evaluate_model_metrics(model_name):
    print(f"Evaluating {model_name}...")
    try:
        # Load the best model checkpoint
        checkpoint_path = f"results/checkpoints/{model_name}_best.pth"
        if not os.path.exists(checkpoint_path):
            print(f"Warning: Checkpoint not found for {model_name}. Skipping evaluation.")
            return None

        model = create_model(model_name, NUM_CLASSES)
        model.load_state_dict(torch.load(checkpoint_path, map_location=DEVICE))
        model = model.to(DEVICE)
        model.eval()

        # Evaluate on test set
        test_loss, test_accuracy = validate(model, test_loader, criterion)

        # Calculate inference time
        start_time = time.time()
        with torch.no_grad():
            for images, _ in test_loader:
                images = images.to(DEVICE)
                _ = model(images)
        end_time = time.time()
        inference_time_per_image_ms = (end_time - start_time) / len(test_loader.dataset) * 1000

        # Count parameters
        total_parameters = count_parameters(model)

        # Calculate F1-score (macro average)
        all_preds = []
        all_labels = []
        with torch.no_grad():
            for images, labels in test_loader:
                images = images.to(DEVICE)
                outputs = model(images)
                _, predicted = torch.max(outputs, 1)
                all_preds.extend(predicted.cpu().numpy())
                all_labels.extend(labels.cpu().numpy())

        f1 = f1_score(all_labels, all_preds, average='macro')

        return {
            "Model": model_name,
            "Accuracy": test_accuracy,
            "F1-Score": f1,
            "Inference Time (ms)": inference_time_per_image_ms,
            "Total Parameters": total_parameters
        }

    except Exception as e:
        print(f"Error evaluating {model_name}: {e}")
        return None

